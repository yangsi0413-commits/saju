  function branchRelation(x, y) {
    const rels = findRel([{ label: 'A', branch: x }, { label: 'B', branch: y }]);
    if (!rels.length) return x === y ? { type: '같음', score: 66, name: `${E.BRANCHES_HANJA[x]}${E.BRANCHES_HANJA[y]}`, text: '같은 글자라 생각과 습관이 닮았습니다. 편하지만 서로의 단점도 똑같이 보입니다.' }
      : { type: '무난', score: 62, name: '', text: '특별히 끌어당기거나 부딪히는 관계가 없어 무난합니다.' };
    const best = rels.sort((r1, r2) => (BRANCH_REL_SCORE[r2.type] ?? 60) - (BRANCH_REL_SCORE[r1.type] ?? 60));
    const pos = best.filter(r => BRANCH_REL_SCORE[r.type] >= 70);
    const neg = best.filter(r => BRANCH_REL_SCORE[r.type] < 60);
    let score = pos.length ? BRANCH_REL_SCORE[pos[0].type] : 62;
    for (const r of neg) score -= (62 - BRANCH_REL_SCORE[r.type]);
    const main = pos[0] || neg[0];
    return { type: main.type, score: clamp(score, 20, 95), name: best.map(r => r.name).join(', '), text: [pos[0], neg[0]].filter(Boolean).map(r => BRANCH_REL_TEXT[r.type]).join(' ') };
  }
