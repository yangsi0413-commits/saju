  E.BRANCHES_HANJA.forEach((h, i) => { HANJA_READING[h] = E.BRANCHES[i]; });
  Object.assign(HANJA_READING, { 木: '목', 火: '화', 土: '토', 金: '금', 水: '수' });
  const hasBatchim = (w) => {
    const str = String(w).replace(/["'”’\s]+$/, '').replace(/\([^)]*\)$/, '');
    const last = str[str.length - 1] || '';
    const c = (HANJA_READING[last] || last).charCodeAt(0);
    return c >= 0xAC00 && c <= 0xD7A3 && (c - 0xAC00) % 28 !== 0;
  };
  // josa('목', '이/가') → '목이', josa('경금(庚金)', '은/는') → '경금(庚金)은'
  const josa = (w, pair) => { const [a, b] = pair.split('/'); return w + (hasBatchim(w) ? a : b); };
  // 괄호나 한자 뒤에 붙은 조사를 받침에 맞게 고친다 (예: "巳(편관)이" → "巳(편관)가")
  const PAIRS = { 은: '은/는', 는: '은/는', 이: '이/가', 가: '이/가', 을: '을/를', 를: '을/를', 과: '과/와', 와: '과/와' };
  const fixJosa = (text) => text.replace(
    /([가-힣\u4e00-\u9fff]+(?:\([^)]*\))?|[\u4e00-\u9fff])(은|는|이|가|을|를|과|와)(?=[\s,.!?:]|$)/g,
    (m, word, j) => (/[)\u4e00-\u9fff]$/.test(word) ? josa(word, PAIRS[j]) : m));
  const elName = (e) => `${e}(${ELEMENT_INFO[e].hanja})`;
  const elIdx = (e) => ELS.indexOf(e);
  const dayEl = (s) => s.dayMaster.element;
  const groupElement = (s, g) => ELS[(elIdx(dayEl(s)) + GROUPS.indexOf(g)) % 5];
  const groupCount = (s, g) => Object.entries(s.tenGodCount).filter(([k]) => GOD_GROUP[k] === g).reduce((a, [, v]) => a + v, 0);
  const POS = [['year', '년'], ['month', '월'], ['day', '일'], ['hour', '시']];
  const isMale = (s) => s.gender === 'M' || s.gender === '남';

  // 일간을 제외한 모든 글자: { label, hanja, ko, element, yinyang, god }
  function chars(s) {
    const out = [];
    for (const [k, l] of POS) {
      const p = s.pillars[k];
      if (!p) continue;
      if (k !== 'day') out.push({ label: l + '간', hanja: E.STEMS_HANJA[p.stem], ko: E.STEMS[p.stem], element: p.stemElement, yinyang: p.stemYinYang, god: p.stemTenGod });
      out.push({ label: l + '지', hanja: E.BRANCHES_HANJA[p.branch], ko: E.BRANCHES[p.branch], element: p.branchElement, yinyang: p.branchYinYang, god: p.branchTenGod });
    }
    return out;
  }

  const section = (id, title, lead, paragraphs, why = []) => ({
    id, title, lead: fixJosa(lead),
    paragraphs: paragraphs.filter(Boolean).map(fixJosa),
    why: why.filter(Boolean).map(fixJosa),
  });

