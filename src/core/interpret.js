  // 들어오는 글자의 오행이 용신·희신이면 +, 기신·구신이면 -. 일지와의 합충도 반영
  function luckScore(s, lp) {
    const y = s.yongsin;
    const w = (e) => (e === y.yongsin ? 1 : e === y.huisin ? 0.6 : e === y.gisin ? -1 : e === y.gusin ? -0.6 : 0);
    const label = (e) => (e === y.yongsin ? '용신' : e === y.huisin ? '희신' : e === y.gisin ? '기신' : e === y.gusin ? '구신' : '한신');
    let score = 55 + 14 * w(lp.stemElement) + 18 * w(lp.branchElement);
    const why = [
      `천간 ${E.STEMS_HANJA[lp.stem]}(${lp.stemElement}) — 나에게 ${label(lp.stemElement)}`,
      `지지 ${E.BRANCHES_HANJA[lp.branch]}(${lp.branchElement}) — 나에게 ${label(lp.branchElement)}`,
    ];
    for (const r of lp.relations || []) {
      if (!r.members.includes('일지') && !r.members.includes('일간')) continue;
      const d = { 충: -8, 천간충: -5, 형: -4, 원진: -4, 해: -3, 파: -3, 육합: 4, 반합: 3, 삼합: 5, 천간합: 3, 방합: 3 }[r.type] || 0;
      if (d) { score += d; why.push(`${r.name}: 나 자신·배우자궁과 ${d > 0 ? '합(+)' : '부딪힘(-)'}`); }
    }
    score = Math.round(Math.max(15, Math.min(95, score)));
    const grade = score >= 80 ? '아주 좋음' : score >= 65 ? '좋음' : score >= 50 ? '보통' : score >= 35 ? '조심' : '주의';
    return { score, grade, why };
  }

